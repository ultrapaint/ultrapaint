import path from "node:path";
import {
  REGISTRY_GLOBAL,
  REGISTRY_MEMBERS,
} from "@ultrapaint/contracts/page-runtime";
import type { PreviewInput } from "@ultrapaint/framework-api/node";
import { toPosix } from "@ultrapaint/shared/path";
import { ASSET_PATH } from "./asset-route.ts";
import type { PreviewBundles } from "./build.ts";
import { PUBLIC_FILES_ID } from "./public-urls.ts";
import type { ServeOptions } from "./serve-config.ts";

const LEADING_NON_DOT_RE = /^(?!\.)/;
const LEADING_NON_SLASH_RE = /^(?!\/)/;

/** Packages there must be one copy of on the page, whoever imports them. */
const SINGLETONS = ["react", "react-dom", "scheduler"];

export const OPTIONS_FILE = "preview.json";

/** The generated registry of the component modules instances import. */
export const COMPONENTS_FILE = "components.ts";

/**
 * The registry module: one lazy import per component module. It accepts its own updates, so a
 * module added while the preview runs reaches it without a reload.
 */
export const componentsModule = (specifiers: readonly string[]): string => {
  const entries = [...new Set(specifiers)]
    .sort()
    .map((s) => `  ${JSON.stringify(s)}: () => import(${JSON.stringify(s)}),`)
    .join("\n");
  return `// Generated by ultrapaint: the component modules the designs use. Rewritten as they change.
export const components: Record<string, () => Promise<unknown>> = {
${entries}
};

if (import.meta.hot) {
  import.meta.hot.accept((next) => {
    if (next) {
      (window as unknown as { ${REGISTRY_GLOBAL}?: { ${REGISTRY_MEMBERS.setComponents}: (c: unknown) => void } }).${REGISTRY_GLOBAL}?.${REGISTRY_MEMBERS.setComponents}(next.components);
    }
  });
}
`;
};

/** The module the editor imports to draw frames in its own page (ADR 0034). */
export const EDITOR_FILE = "editor.ts";

/** Where the editor imports the preview from: `/preview/@fs/<dir>/editor.ts`. */
export const editorEntry = (input: Pick<PreviewInput, "base" | "dir">) =>
  `${input.base}@fs${toPosix(path.join(input.dir, EDITOR_FILE)).replace(LEADING_NON_SLASH_RE, "/")}`;

/**
 * Contents of the generated directory the preview is served from: the module the editor's page
 * imports, the registry and the stylesheet it loads, and the options of the serve script. No Vite
 * config is written; the serve script builds it from the anchor's own and from these options.
 */
export const previewFiles = (
  input: PreviewInput,
  bundles: PreviewBundles,
  /** The anchor has Tailwind's Vite plugin, which the preview then inherits. */
  tailwind: boolean
): Record<string, string> => {
  const { designsDir, dir, settings } = input;
  const include = [
    designsDir,
    ...settings.libraryDirs.map((d) => path.join(input.root, d)),
  ];
  const fsPath = (file: string) =>
    `@fs${toPosix(file).replace(LEADING_NON_SLASH_RE, "/")}`;
  /** What a module imports: Vite puts the base in front. */
  const fsUrl = (file: string) => `/${fsPath(file)}`;
  /** What the browser asks for as it is: with the base. */
  const servedUrl = (file: string) => `${input.base}${fsPath(file)}`;
  const assets = `${input.base.slice(0, -1)}${ASSET_PATH}`;

  const options: ServeOptions = {
    anchorDir: input.anchorDir,
    base: input.base,
    bundleDir: bundles.dir,
    designsDir,
    dir,
    entries: [
      toPosix(path.join(dir, EDITOR_FILE)),
      toPosix(path.join(dir, COMPONENTS_FILE)),
      ...settings.libraryDirs.map(
        (d) => `${toPosix(path.join(input.root, d))}/**/*.tsx`
      ),
      // The designs directory links the anchor's dependencies in as its own `node_modules`, so
      // that editors resolve what the pages import; the scan must not walk into them.
      ...include.map((d) => `!${toPosix(d)}/**/node_modules/**`),
    ],
    include,
    root: input.root,
    singletons: SINGLETONS,
    tailwind,
  };

  const css = [
    // The repository's stylesheets and what makes every token a custom property: the style
    // system's (ADR 0024).
    ...input.styles,
    // The page is drawn from documents; its body is the design's, edge to edge.
    "html, body { margin: 0; }",
    "html, body, #root { min-height: 100%; }",
    "",
  ].join("\n");

  const providersImport = settings.providersModule
    ? `import Providers from ${JSON.stringify(toPosix(path.relative(dir, path.join(designsDir, settings.providersModule))).replace(LEADING_NON_DOT_RE, "./"))};`
    : "const Providers = undefined;";

  // The hooks are in place before the stylesheet's module runs: Vite's client hands what it
  // loads to the editor's frames instead of the editor's head. They are a module of their own,
  // imported first, because an entry's imports all run before its body: `host.css` and the
  // repository's modules (whose stylesheets the client also loads) run before `createPreview`,
  // and a stylesheet the client loads with no hooks in place goes to the editor's head, never to
  // a frame. Only the hooks run this early; the guards wait for `createPreview` (preview-core's
  // `kernel.ts` says why).
  const editorHooks = `import { installHooks } from ${JSON.stringify(fsUrl(bundles.editor))};

installHooks();
`;

  const editor = `import "./editor-hooks.ts";
import "./host.css";
import { createPreview } from ${JSON.stringify(fsUrl(bundles.editor))};

export { onReloadRequest } from ${JSON.stringify(fsUrl(bundles.editor))};
import { components } from "./${COMPONENTS_FILE}";
import { publicFiles } from ${JSON.stringify(PUBLIC_FILES_ID)};
${providersImport}

// What the editor draws its frames with, in its own page (ADR 0034).
export const preview = createPreview({
  assets: ${JSON.stringify(assets)},
  components,
  designsRoot: ${JSON.stringify(servedUrl(designsDir))},
  providers: Providers,
  publicFiles,
  theme: ${JSON.stringify(settings.theme)},
});

if (import.meta.hot) {
  import.meta.hot.on("vite:afterUpdate", () => preview.notifyHmr());
  import.meta.hot.on("vite:error", (e: { err: { message: string; id?: string; loc?: { line: number } } }) =>
    preview.reportError({ message: e.err.message, file: e.err.id, line: e.err.loc?.line }),
  );
}
`;

  return {
    [COMPONENTS_FILE]: componentsModule(input.components),
    [EDITOR_FILE]: editor,
    "editor-hooks.ts": editorHooks,
    "host.css": css,
    [OPTIONS_FILE]: `${JSON.stringify(options, null, 2)}\n`,
  };
};
