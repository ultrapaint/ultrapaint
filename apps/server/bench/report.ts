/**
 * Turns the runs in `docs/feature/benchmarks/` into the table the decision is made from: what a
 * task costs an agent in each arm, and whether it still came out right.
 *
 * Usage: node --experimental-strip-types apps/server/bench/report.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

interface Measurement {
  readonly arm: string;
  readonly failure: string | null;
  readonly seconds: number;
  readonly task: string;
  readonly toolCalls: number;
  readonly toolKinds: Record<string, number>;
}

const dir = path.resolve(import.meta.dirname, "../../../docs/feature/benchmarks");
const runs = readdirSync(dir)
  .filter((name) => name.endsWith(".json"))
  .flatMap(
    (name) => JSON.parse(readFileSync(path.join(dir, name), "utf8")) as Measurement[]
  );

const arms = [...new Set(runs.map((r) => r.arm))];
const tasks = [...new Set(runs.map((r) => r.task))];

const mean = (values: readonly number[]) =>
  values.length === 0
    ? null
    : values.reduce((a, b) => a + b, 0) / values.length;

const cell = (task: string, arm: string) => {
  const mine = runs.filter((r) => r.task === task && r.arm === arm);
  const calls = mean(mine.map((r) => r.toolCalls));
  if (calls === null) {
    return "—";
  }
  const seconds = mean(mine.map((r) => r.seconds)) ?? 0;
  const failed = mine.filter((r) => r.failure !== null).length;
  return `${calls.toFixed(0)} calls · ${seconds.toFixed(0)}s${failed > 0 ? ` · ${failed}/${mine.length} wrong` : ""}`;
};

const lines = [
  "| Task | " + arms.join(" | ") + " |",
  "|---|" + arms.map(() => "---").join("|") + "|",
  ...tasks.map(
    (task) => `| ${task} | ${arms.map((arm) => cell(task, arm)).join(" | ")} |`
  ),
];

const totals = arms.map((arm) => {
  const mine = runs.filter((r) => r.arm === arm);
  return `${arm}: ${(mean(mine.map((r) => r.toolCalls)) ?? 0).toFixed(1)} calls on average over ${mine.length} runs`;
});

const kinds = arms.map((arm) => {
  const counts: Record<string, number> = {};
  for (const run of runs.filter((r) => r.arm === arm)) {
    for (const [kind, n] of Object.entries(run.toolKinds)) {
      counts[kind] = (counts[kind] ?? 0) + n;
    }
  }
  const total = Object.values(counts).reduce((a, b) => a + b, 0);
  const shown = Object.entries(counts)
    .sort(([, a], [, b]) => b - a)
    .map(([kind, n]) => `${kind} ${n}`)
    .join(", ");
  return `${arm}: ${total} tool calls — ${shown}`;
});

const report = [
  "# Benchmark: what a task costs an agent",
  "",
  "Generated by `apps/server/bench/report.ts` from the runs in this directory.",
  "",
  ...lines,
  "",
  "## Totals",
  "",
  ...totals.map((line) => `- ${line}`),
  "",
  "## Where the calls go",
  "",
  ...kinds.map((line) => `- ${line}`),
  "",
].join("\n");

writeFileSync(path.join(dir, "README.md"), report);
process.stdout.write(report);
